-- Adopt pre-tenancy workspaces (sheets without a spreadsheet row) as
-- system-owned spreadsheets so the FK below always holds.
INSERT INTO ledger_spreadsheet (spreadsheet_id, user_id, name)
SELECT DISTINCT workspace, 0, workspace FROM ledger_sheet
ON CONFLICT DO NOTHING;

DO $$
BEGIN
    ALTER TABLE ledger_sheet
        ADD CONSTRAINT ledger_sheet_workspace_fkey
        FOREIGN KEY (workspace)
        REFERENCES ledger_spreadsheet (spreadsheet_id)
        ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
